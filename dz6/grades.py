SQLITE_FILE = Path(__file__).resolve().with_name("grades.sqlite3")


class GradeDatabase:
    def __init__(self, connection, backend):
        self.connection = connection
        self.backend = backend
        self.marker = "?" if backend == "SQLite" else "%s"

    ## Создание двух связанных таблиц
    def create_tables(self):
        key = "INTEGER PRIMARY KEY"
        if self.backend == "PostgreSQL":
            key = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

        cursor = self.connection.cursor()
        try:
            cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS subjects (
                    id {key},
                    name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
                )
            """)
            cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS grades (
                    id {key},
                    subject_id INTEGER NOT NULL REFERENCES subjects(id),
                    value INTEGER NOT NULL CHECK (value BETWEEN 2 AND 5)
                )
            """)
            self.connection.commit()
        except Exception:
            self.connection.rollback()
            raise
        finally:
            cursor.close()

    ## Добавление предмета (если нужно) и оценки
    def add_grade(self, subject, value):
        cursor = self.connection.cursor()
        try:
            cursor.execute(
                f"SELECT id FROM subjects WHERE name = {self.marker}",
                (subject,)
            )
            found = cursor.fetchone()

            if found is None:
                cursor.execute(
                    f"INSERT INTO subjects (name) VALUES ({self.marker})",
                    (subject,)
                )
                cursor.execute(
                    f"SELECT id FROM subjects WHERE name = {self.marker}",
                    (subject,)
                )
                subject_id = cursor.fetchone()[0]
            else:
                subject_id = found[0]

            cursor.execute(
                f"INSERT INTO grades (subject_id, value) "
                f"VALUES ({self.marker}, {self.marker})",
                (subject_id, value)
            )
            self.connection.commit()
        except Exception:
            self.connection.rollback()
            raise
        finally:
            cursor.close()

    ## Удаление одной оценки по её ID
    def delete_grade(self, grade_id):
        cursor = self.connection.cursor()
        try:
            cursor.execute(
                f"DELETE FROM grades WHERE id = {self.marker}",
                (grade_id,)
            )
            self.connection.commit()
        except Exception:
            self.connection.rollback()
            raise
        finally:
            cursor.close()

    ## Получение данных с помощью SELECT и JOIN
    def read_data(self):
        cursor = self.connection.cursor()
        try:
            cursor.execute("SELECT id, name FROM subjects ORDER BY id")
            subjects = cursor.fetchall()

            cursor.execute("""
                SELECT grades.id, subjects.name, grades.value
                FROM grades
                JOIN subjects ON subjects.id = grades.subject_id
                ORDER BY grades.id DESC
            """)
            grades = cursor.fetchall()
            self.connection.commit()
            return subjects, grades
        except Exception:
            self.connection.rollback()
            raise
        finally:
            cursor.close()

    def close(self):
        self.connection.close()


