    def make_table(self, headers):
        table = QTableWidget(0, len(headers))
        table.setHorizontalHeaderLabels(headers)
        table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        table.setSelectionMode(QAbstractItemView.SelectionMode.SingleSelection)
        table.setColumnWidth(0, 105)
        table.setColumnWidth(1, 300)
        table.horizontalHeader().setStretchLastSection(True)
        table.verticalHeader().hide()
        return table

    ## Окно настройки PostgreSQL
    def postgres_settings(self):
        dialog = QDialog(self)
        dialog.setWindowTitle("Подключение к PostgreSQL")
        form = QFormLayout(dialog)
        host = QLineEdit("localhost")
        port = QSpinBox()
        port.setRange(1, 65535)
        port.setValue(5432)
        dbname = QLineEdit("grade_calculator")
        username = QLineEdit("postgres")
        password = QLineEdit()
        password.setEchoMode(QLineEdit.EchoMode.Password)

        form.addRow("Сервер:", host)
        form.addRow("Порт:", port)
        form.addRow("База данных:", dbname)
        form.addRow("Пользователь:", username)
        form.addRow("Пароль:", password)

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Ok |
            QDialogButtonBox.StandardButton.Cancel
        )
        buttons.accepted.connect(dialog.accept)
        buttons.rejected.connect(dialog.reject)
        form.addRow(buttons)

        if dialog.exec() != QDialog.DialogCode.Accepted:
            return None

        if not host.text().strip() or not dbname.text().strip() or not username.text().strip():
            QMessageBox.warning(self, "Ошибка", "Заполните параметры подключения.")
            return None

        return {
            "host": host.text().strip(),
            "port": port.value(),
            "dbname": dbname.text().strip(),
            "user": username.text().strip(),
            "password": password.text(),
            "connect_timeout": 5
        }

    ## Подключение к выбранной базе данных
    def switch_database(self, index):
        backend = self.backend.itemText(index)
        old_index = self.backend.findText(self.database.backend) if self.database else 0

        if self.database is not None and backend == self.database.backend:
            self.refresh_tables()
            return

        connection = None
        try:
            if backend == "SQLite":
                connection = sqlite3.connect(SQLITE_FILE, timeout=5)
                connection.execute("PRAGMA foreign_keys = ON")
                location = SQLITE_FILE.name
            else:
                try:
                    import psycopg
                except ImportError:
                    QMessageBox.warning(
                        self, "PostgreSQL",
                        'Установите драйвер: python -m pip install "psycopg[binary]"'
                    )
                    self.backend.setCurrentIndex(old_index)
                    return

                settings = self.postgres_settings()
                if settings is None:
                    self.backend.setCurrentIndex(old_index)
                    return
                connection = psycopg.connect(**settings)
                location = settings["dbname"]

            candidate = GradeDatabase(connection, backend)
            candidate.create_tables()
            subjects, grades = candidate.read_data()
        except Exception as error:
            if connection is not None:
                connection.close()
            self.backend.setCurrentIndex(old_index)
            QMessageBox.warning(self, "Ошибка подключения", str(error))
            return

        if self.database is not None:
            self.database.close()
        self.database = candidate
        self.backend.setCurrentIndex(index)
        self.db_label.setText(f"Подключено: {backend} ({location})")
        self.add_button.setEnabled(True)
        self.delete_button.setEnabled(True)
        self.refresh_button.setEnabled(True)
        self.show_data(subjects, grades)

    ## Отображение предметов и оценок
    def show_data(self, subjects, grades):
        self.grade_rows = grades
        self.grades = [row[2] for row in grades]

        self.subjects_table.setRowCount(len(subjects))
        for i, row in enumerate(subjects):
            for j, value in enumerate(row):
                self.subjects_table.setItem(i, j, QTableWidgetItem(str(value)))

        self.grades_table.setRowCount(len(grades))
        for i, row in enumerate(grades):
            for j, value in enumerate(row):
                self.grades_table.setItem(i, j, QTableWidgetItem(str(value)))

        self.update_average()

    ## Повторное чтение данных из выбранной базы
    def refresh_tables(self):
        if self.database is None:
            return
        try:
            subjects, grades = self.database.read_data()
        except Exception as error:
            QMessageBox.warning(self, "Ошибка чтения", str(error))
            return
        self.show_data(subjects, grades)

    ## Сохранение новой оценки
    def add_grade(self):
        if self.database is None:
            return
        subject = self.subject_input.text().strip()
        if not subject or len(subject) > 100 or "\x00" in subject:
            QMessageBox.warning(self, "Ошибка", "Введите название предмета (до 100 символов).")
            return

        grade = int(self.grade_input.currentText())
        try:
            self.database.add_grade(subject, grade)
        except Exception as error:
            QMessageBox.warning(self, "Ошибка сохранения", str(error))
            return

        self.refresh_tables()
        self.tabs.setCurrentWidget(self.grades_table)
        self.grades_table.clearSelection()

    ## Удаление выбранной оценки из базы
    def delete_grade(self):
        index = self.grades_table.currentRow()
        if index < 0 or index >= len(self.grade_rows):
            QMessageBox.warning(self, "Ошибка", "Выберите оценку в таблице «Оценки».")
            return
        grade_id = self.grade_rows[index][0]
        try:
            self.database.delete_grade(grade_id)
        except Exception as error:
            QMessageBox.warning(self, "Ошибка удаления", str(error))
            return
        self.refresh_tables()

    ## Средний балл по оценкам из выбранной базы
    def update_average(self):
        count = len(self.grades)
        self.count_label.setText(f"Количество оценок: {count}")
        if count:
            average = sum(self.grades) / count
            self.average_label.setText(f"Средний балл: {average:.2f}")
        else:
            self.average_label.setText("Средний балл: —")
        self.result.clear()

    ## Расчёт количества пятёрок для нужного среднего
    def calculate(self):
        if not self.grades:
            QMessageBox.warning(self, "Ошибка", "Сначала добавьте оценки!")
            return

        desired = float(self.target.currentText())
        total = sum(self.grades)
        count = len(self.grades)

        if total / count >= desired:
            self.result.setText("Желаемый средний балл уже достигнут!")
            return

        needed = 0
        while (total + 5 * needed) / (count + needed) < desired:
            needed += 1

        if needed % 10 == 1 and needed % 100 != 11:
            word = "пятёрку"
        elif needed % 10 in (2, 3, 4) and needed % 100 not in (12, 13, 14):
            word = "пятёрки"
        else:
            word = "пятёрок"

        self.result.setText(
            f"Для среднего балла {desired} нужно получить ещё {needed} {word}."
        )

    ## Закрытие соединения при завершении программы
    def closeEvent(self, event):
        if self.database is not None:
            self.database.close()
        super().closeEvent(event)


